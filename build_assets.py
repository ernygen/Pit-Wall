"""
Copy Team Principal's own flag + team-logo assets into the site folder.

Usage (defaults point at the Steam install on E:):
    python build_assets.py
    python build_assets.py --game "E:\\SteamLibrary\\steamapps\\common\\Team Principal A Racing Manager" --out .
    python build_assets.py --packs 2026pfm anka   (only these data packs)

What it does:
  1. Copies ui/assets/flags/*.png -> <out>/flags/  (~60 KB, full coverage).
  2. Copies EVERY logo of every data pack (or --packs subset) into
     <out>/logos/<pack>/, resized to 128 px for web (~96% smaller, identical
     on screen since badges render at ~28 px).
  3. Writes <out>/assets.js with:
       window.PITWALL_FLAGS            (flag basenames)
       window.PITWALL_LOGO_PACKS       ({pack: {norm_name: filename}})
       window.PITWALL_LOGO_PACK_LIST   ([packs...])
     The site visitor picks a pack in Settings; matching (exact, then
     startswith/contains) happens at runtime in the browser.

Re-run it any time your game gains new packs.
"""
import argparse
import json
import os
import re
import shutil
import unicodedata

IMG_EXTS = ('.png', '.jpg', '.jpeg', '.webp')
LOGO_SIZE = 128


def norm(s):
    s = unicodedata.normalize('NFD', (s or '').lower())
    s = ''.join(c for c in s if unicodedata.category(c) != 'Mn')
    return re.sub(r'[^a-z0-9]', '', s)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--game', default=r'E:\SteamLibrary\steamapps\common\Team Principal A Racing Manager')
    ap.add_argument('--out', default=os.path.dirname(os.path.abspath(__file__)))
    ap.add_argument('--packs', nargs='*', default=None,
                    help='only these data packs (default: all with a logos folder)')
    ap.add_argument('--size', type=int, default=LOGO_SIZE)
    args = ap.parse_args()
    game = args.game
    out = args.out

    # ---- 1. flags (whole folder, tiny) ----
    src_flags = os.path.join(game, 'ui', 'assets', 'flags')
    dst_flags = os.path.join(out, 'flags')
    os.makedirs(dst_flags, exist_ok=True)
    flag_names = []
    if os.path.isdir(src_flags):
        for f in sorted(os.listdir(src_flags)):
            if f.lower().endswith(IMG_EXTS):
                shutil.copy2(os.path.join(src_flags, f), os.path.join(dst_flags, f))
                flag_names.append(os.path.splitext(f)[0].lower())
    print('flags: %d files -> %s' % (len(flag_names), dst_flags))

    # ---- 2. logos per pack ----
    try:
        from PIL import Image
        have_pil = True
    except ImportError:
        have_pil = False
        print('WARNING: Pillow missing — copying originals (large). pip install pillow')
    data_dir = os.path.join(game, 'data')
    packs = {}
    total_files, total_bytes = 0, 0
    for pack in sorted(os.listdir(data_dir)):
        if args.packs and pack not in args.packs:
            continue
        ldir = os.path.join(data_dir, pack, 'assets', 'logos')
        if not os.path.isdir(ldir):
            continue
        dst = os.path.join(out, 'logos', pack)
        os.makedirs(dst, exist_ok=True)
        manifest = {}
        for f in sorted(os.listdir(ldir)):
            if not f.lower().endswith(IMG_EXTS):
                continue
            src = os.path.join(ldir, f)
            key = norm(os.path.splitext(f)[0])
            if not key or key in manifest:
                continue
            dstf = os.path.join(dst, f)
            try:
                if have_pil:
                    im = Image.open(src)
                    im.thumbnail((args.size, args.size), Image.LANCZOS)
                    if im.mode in ('RGBA', 'LA'):
                        im.save(dstf, optimize=True)
                    else:
                        im.convert('RGB').save(dstf, optimize=True)
                else:
                    shutil.copy2(src, dstf)
                manifest[key] = f
                total_files += 1
                total_bytes += os.path.getsize(dstf)
            except Exception as e:
                print('  skip %s/%s (%s)' % (pack, f, e))
        packs[pack] = manifest
        print('logos/%s: %d files' % (pack, len(manifest)))

    with open(os.path.join(out, 'assets.js'), 'w', encoding='utf-8') as fh:
        fh.write('// Auto-generated by build_assets.py — game flag/logo manifests.\n')
        fh.write('// Loaded via <script> so it also works over file:// (no fetch needed).\n')
        fh.write('window.PITWALL_FLAGS = ')
        json.dump(sorted(flag_names), fh)
        fh.write(';\nwindow.PITWALL_LOGO_PACKS = ')
        json.dump(packs, fh, sort_keys=True)
        fh.write(';\nwindow.PITWALL_LOGO_PACK_LIST = ')
        json.dump(sorted(packs.keys()), fh)
        fh.write(';\n')
    print('total: %d logos, %.1f MB -> %s' % (total_files, total_bytes / 1048576, os.path.join(out, 'assets.js')))


if __name__ == '__main__':
    main()
