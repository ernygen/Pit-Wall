"""
Copy Team Principal's own flag + team-logo assets into the site folder.

Usage (defaults point at the Steam install on E:):
    python build_assets.py
    python build_assets.py --game "E:\\SteamLibrary\\steamapps\\common\\Team Principal A Racing Manager" --saves "<game>\\saves" --out .

What it does:
  1. Copies ui/assets/flags/*.png -> <out>/flags/  (~60 KB, full coverage)
     and writes <out>/flags.json  (list of basenames, e.g. ["dutch", ...]).
  2. Scans every season*.json in the saves folder for team names,
     finds each team's logo across ALL data packs' assets/logos folders
     (exact name match wins, then startswith/contains), copies the winners
     into <out>/logos/ and writes <out>/logos.json
     ({normalized_team_name: filename}).

Re-run it any time you start a career with new teams.
"""
import argparse
import glob
import json
import os
import re
import shutil
import unicodedata

IMG_EXTS = ('.png', '.jpg', '.jpeg', '.webp')


def norm(s):
    s = unicodedata.normalize('NFD', (s or '').lower())
    s = ''.join(c for c in s if unicodedata.category(c) != 'Mn')
    return re.sub(r'[^a-z0-9]', '', s)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--game', default=r'E:\SteamLibrary\steamapps\common\Team Principal A Racing Manager')
    ap.add_argument('--saves', default=None)
    ap.add_argument('--out', default=os.path.dirname(os.path.abspath(__file__)))
    args = ap.parse_args()
    game = args.game
    saves = args.saves or os.path.join(game, 'saves')
    out = args.out

    # ---- 1. flags (whole folder, tiny) ----
    src_flags = os.path.join(game, 'ui', 'assets', 'flags')
    dst_flags = os.path.join(out, 'flags')
    os.makedirs(dst_flags, exist_ok=True)
    flag_names = []
    if os.path.isdir(src_flags):
        for f in sorted(os.listdir(src_flags)):
            if f.lower().endswith(IMG_EXTS):
                shutil.copy2(os.path.join(src_flags, f), os.path.join(dst_flags, f))
                flag_names.append(os.path.splitext(f)[0].lower())
    with open(os.path.join(out, 'assets.js'), 'w', encoding='utf-8') as fh:
        fh.write('// Auto-generated by build_assets.py — game flag/logo manifests.\n')
        fh.write('// Loaded via <script> so it also works over file:// (no fetch needed).\n')
        fh.write('window.PITWALL_FLAGS = ')
        json.dump(sorted(flag_names), fh)
        fh.write(';\n')
    print('flags: %d files -> %s' % (len(flag_names), dst_flags))

    # ---- 2. collect teams (+ their data packs) from saves ----
    teams = {}  # team name -> set of data_packs
    save_files = sorted(glob.glob(os.path.join(saves, 'season*.json')))
    for sf in save_files:
        try:
            with open(sf, encoding='utf-8') as fh:
                d = json.load(fh)
        except Exception as e:
            print('skip %s (%s)' % (os.path.basename(sf), e))
            continue
        pack = d.get('data_pack') or ''
        names = set((d.get('teams') or {}).keys())
        for r in (d.get('race_results') or []):
            names.update((r.get('driver_teams') or {}).values())
        for n in names:
            if n:
                teams.setdefault(n, set()).add(pack)
    print('teams found in saves: %d' % len(teams))

    # ---- 3. index every logo in every data pack ----
    logo_index = []  # (norm_name, pack, filename, fullpath, size)
    data_dir = os.path.join(game, 'data')
    for pack in sorted(os.listdir(data_dir)):
        ldir = os.path.join(data_dir, pack, 'assets', 'logos')
        if not os.path.isdir(ldir):
            continue
        for f in os.listdir(ldir):
            if not f.lower().endswith(IMG_EXTS):
                continue
            fp = os.path.join(ldir, f)
            try:
                size = os.path.getsize(fp)
            except OSError:
                continue
            logo_index.append((norm(os.path.splitext(f)[0]), pack, f, fp, size))

    def score(tn, fn):
        if not tn or not fn:
            return -1
        if fn == tn:
            return 3
        if fn.startswith(tn) or tn.startswith(fn):
            return 2
        if tn in fn or fn in tn:
            return 1
        return -1

    dst_logos = os.path.join(out, 'logos')
    os.makedirs(dst_logos, exist_ok=True)
    manifest = {}
    missing = []
    for team in sorted(teams):
        tn = norm(team)
        packs = teams[team]
        cands = [(score(tn, fn), (0 if pack in packs else 1), -size, pack, f, fp)
                 for (fn, pack, f, fp, size) in logo_index if score(tn, fn) >= 0]
        if not cands:
            missing.append(team)
            continue
        cands.sort()
        best = cands[-1]
        _, _, _, pack, f, fp = best
        dst = os.path.join(dst_logos, f)
        if os.path.exists(dst) and os.path.getsize(dst) != os.path.getsize(fp):
            # same filename, different art in another pack -> keep both
            base, ext = os.path.splitext(f)
            f = '%s__%s%s' % (re.sub(r'\W+', '', pack), base, ext)
            dst = os.path.join(dst_logos, f)
        shutil.copy2(fp, dst)
        manifest[tn] = f
    with open(os.path.join(out, 'assets.js'), 'a', encoding='utf-8') as fh:
        fh.write('window.PITWALL_LOGOS = ')
        json.dump(manifest, fh, indent=1, sort_keys=True)
        fh.write(';\n')
    print('logos: %d matched -> %s' % (len(manifest), dst_logos))
    if missing:
        print('logos MISSING (%d), color-badge fallback will be used:' % len(missing))
        for m in missing:
            print('  - %s' % m)


if __name__ == '__main__':
    main()
